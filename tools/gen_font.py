#!/usr/bin/env python3
"""Generate a tiny 1-bit bitmap font (ASCII 32..126) as a Rust source file.

Usage: python3 tools/gen_font.py /path/to/DejaVuSansMono.ttf > crates/lw-overlay-layer/src/font.rs
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H, SIZE = 8, 13, 11
font = ImageFont.truetype(sys.argv[1], SIZE)
rows = []
for c in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, 0), chr(c), fill=255, font=font)
    glyph = []
    for y in range(H):
        bits = 0
        for x in range(W):
            if img.getpixel((x, y)) > 110:
                bits |= 1 << (W - 1 - x)
        glyph.append(bits)
    rows.append(glyph)
print("// Generated by tools/gen_font.py from DejaVu Sans Mono. Do not edit.")
print(f"pub const GLYPH_W: usize = {W};")
print(f"pub const GLYPH_H: usize = {H};")
print(f"pub static GLYPHS: [[u8; {H}]; 95] = [")
for g in rows:
    print("    [" + ", ".join(f"0x{b:02x}" for b in g) + "],")
print("];")
